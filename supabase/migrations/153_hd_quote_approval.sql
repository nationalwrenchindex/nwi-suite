-- =============================================================================
-- 153  HD quote approval, and quote -> work order
-- =============================================================================
--
-- ADDITIVE ONLY. 14 nullable columns across two existing tables (6 on hd_quotes,
-- 8 on hd_work_orders), plus two partial unique indexes. No table is created or
-- dropped, no column is dropped, no existing row is modified, nothing is backfilled.
--
-- -- WHAT THIS IS FOR ------------------------------------------------------
--
-- Kurt builds an HD quote, sends it, the customer approves it, and it becomes an HD
-- work order with nothing retyped. Today none of that is possible:
--
--   * hd_quotes has NO public_token and there is no public route, so there is no link
--     to send a customer.
--   * hd_quotes.status has a CHECK allowing 'approved' and 'declined', and NOTHING in
--     the codebase has ever written either value. The states are unreachable.
--   * hd_work_orders has no quote_id, so there is no link even if one were created.
--
-- -- WHAT hd_quotes ALREADY RECORDS, SO NOTHING IS ADDED TWICE -------------
--
-- Checked against the live table before writing this. hd_quotes has 57 columns and
-- ALREADY carries every pricing term the work order needs to inherit:
--
--   labor_rate, parts_markup_percent, tax_rate, tax_amount, tax_breakdown,
--   travel_hours, travel_rate, travel_amount,
--   mileage_miles, mileage_rate, mileage_amount,
--   shop_supplies_percent_applied, shop_supplies_cap_applied, shop_supplies_fee,
--   diagnostic_fee, road_call_fee, subtotal_labor, subtotal_parts, total
--
-- So NO terms-snapshot columns are added to hd_quotes. The snapshot already exists;
-- what was missing is anywhere to put it on the receiving side, which is why the tax
-- columns below go onto hd_work_orders.
--
-- -- THE RULE THAT DRIVES THE hd_work_orders COLUMNS -----------------------
--
-- "A document's recorded terms beat current settings." A quote approved tonight at
-- tonight's rate, markup, travel and supplies must produce a work order carrying THOSE
-- numbers, not whatever Settings says next week.
--
-- hd_work_orders already has labor_rate, labor_hours, parts_markup_percent, the three
-- travel columns, the three mileage columns and the three shop-supplies columns, so
-- most of the snapshot can already travel. It has NO tax columns at all - not
-- tax_percent, not tax_amount, not tax_breakdown - so without the three added below,
-- the quote's agreed tax terms would be silently dropped at exactly the hop this
-- migration exists to make lossless.

BEGIN;

-- -----------------------------------------------------------------------------
-- 1. hd_quotes: the approval record
-- -----------------------------------------------------------------------------
ALTER TABLE public.hd_quotes
  -- Same shape as the LD quote token: a UUID with the dashes stripped, generated by
  -- the send route (see src/app/api/quotes/[id]/send/route.ts genToken). 32 hex chars.
  ADD COLUMN IF NOT EXISTS public_token           TEXT,
  ADD COLUMN IF NOT EXISTS approved_at            TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS declined_at            TIMESTAMPTZ,
  -- 'customer_link' when the customer clicked it themselves, 'verbal' when the tech
  -- recorded an approval given over the phone. Matches LD's vocabulary exactly so the
  -- two products do not describe the same act with different words.
  ADD COLUMN IF NOT EXISTS approval_method        TEXT,
  ADD COLUMN IF NOT EXISTS customer_response_note TEXT,
  -- The customer's OWN purchase order number, typed by the customer at approval. Not
  -- the same thing as unit_number, and hd_quotes had no PO field of any kind.
  ADD COLUMN IF NOT EXISTS customer_po_number     TEXT;

-- Unique so a token can never address two quotes. Partial, because every existing row
-- has NULL and a plain unique index would reject all but one of them.
CREATE UNIQUE INDEX IF NOT EXISTS hd_quotes_public_token_key
  ON public.hd_quotes (public_token) WHERE public_token IS NOT NULL;

COMMENT ON COLUMN public.hd_quotes.public_token IS
  'Unguessable token for the customer-facing approval page at /hd/quote/<token>. 32 hex characters, generated the same way LD generates its quote token. NULL until the quote is sent.';
COMMENT ON COLUMN public.hd_quotes.approval_method IS
  'How the approval was obtained: customer_link (the customer clicked it) or verbal (the tech recorded it). Part of the authorization record, so it travels onto the work order.';
COMMENT ON COLUMN public.hd_quotes.customer_po_number IS
  'The customer''s purchase order number, entered by the customer when approving. Distinct from unit_number. Travels onto the work order and from there onto the invoice.';

-- -----------------------------------------------------------------------------
-- 2. hd_work_orders: the link, the authorization, and the missing tax terms
-- -----------------------------------------------------------------------------
ALTER TABLE public.hd_work_orders
  ADD COLUMN IF NOT EXISTS quote_id             UUID REFERENCES public.hd_quotes(id) ON DELETE SET NULL,

  -- THE AUTHORIZATION RECORD. "The approval IS the authorization. The tech does not
  -- re-authorize what the customer signed." These are copied from the quote at
  -- creation and are not the tech's to set.
  ADD COLUMN IF NOT EXISTS authorized_at        TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS authorization_method TEXT,
  ADD COLUMN IF NOT EXISTS customer_po_number   TEXT,

  -- THE MISSING TERMS. hd_work_orders has no tax columns at all, so without these the
  -- quote's agreed tax is lost on conversion. tax_percent rather than tax_rate to
  -- match hd_invoices' own tax_rate/tax_amount pairing conventions is deliberately NOT
  -- done here: hd_quotes calls it tax_rate, so this carries the same VALUE under the
  -- name hd_work_orders' siblings use elsewhere. The mapping is one line in the
  -- conversion route and is commented there.
  ADD COLUMN IF NOT EXISTS tax_percent          NUMERIC(6, 3),
  ADD COLUMN IF NOT EXISTS tax_amount           NUMERIC(10, 2),
  ADD COLUMN IF NOT EXISTS tax_breakdown        JSONB,

  -- hd_quotes records customer_id; hd_work_orders did not, so the customer link was
  -- the one identity field that would have had to be retyped.
  ADD COLUMN IF NOT EXISTS customer_id          UUID;

COMMENT ON COLUMN public.hd_work_orders.quote_id IS
  'The approved quote this work order came from. ON DELETE SET NULL rather than CASCADE: deleting a quote must never delete the work order that is now the record of work being done.';
COMMENT ON COLUMN public.hd_work_orders.authorized_at IS
  'When the CUSTOMER approved the quote, copied from hd_quotes.approved_at. Not when the work order was created and not when a tech looked at it. This is the authorization record.';
COMMENT ON COLUMN public.hd_work_orders.tax_percent IS
  'The tax rate the QUOTE priced at, copied from hd_quotes.tax_rate at approval. A document''s recorded terms beat current settings - this exists so that rule can hold across the quote-to-work-order hop, which previously had nowhere to put it.';

-- -----------------------------------------------------------------------------
-- 3. ONE WORK ORDER PER QUOTE, enforced by the database
-- -----------------------------------------------------------------------------
--
-- Modelled on stock_movement_one_use_per_source (migration 151).
--
-- The recon found that EVERY existing double-convert guard in this codebase is an
-- application-level read-then-write check in a route handler, each with a real race
-- window between the SELECT and the INSERT. A customer who opens the approval link
-- twice, or forwards it to a colleague who clicks at the same moment, is exactly the
-- traffic pattern that loses that race - and the result would be two work orders for
-- one approved job, then two invoices.
--
-- Partial, so the 1,562 existing work orders with NULL quote_id do not collide.
CREATE UNIQUE INDEX IF NOT EXISTS hd_work_orders_one_per_quote
  ON public.hd_work_orders (quote_id) WHERE quote_id IS NOT NULL;

COMMENT ON INDEX public.hd_work_orders_one_per_quote IS
  'One work order per quote, enforced here rather than in a route handler. A second concurrent approval of the same quote fails with 23505 and the application returns the work order that already exists. This cannot be bypassed by a code path that forgets to check.';

-- -----------------------------------------------------------------------------
-- 4. Check it
-- -----------------------------------------------------------------------------
-- Expect 6 rows.
SELECT column_name, data_type, is_nullable
FROM   information_schema.columns
WHERE  table_schema = 'public' AND table_name = 'hd_quotes'
  AND  column_name IN ('public_token', 'approved_at', 'declined_at',
                       'approval_method', 'customer_response_note', 'customer_po_number')
ORDER  BY column_name;

-- Expect 8 rows.
SELECT column_name, data_type, is_nullable
FROM   information_schema.columns
WHERE  table_schema = 'public' AND table_name = 'hd_work_orders'
  AND  column_name IN ('quote_id', 'authorized_at', 'authorization_method',
                       'customer_po_number', 'tax_percent', 'tax_amount',
                       'tax_breakdown', 'customer_id')
ORDER  BY column_name;

-- Expect both indexes.
SELECT indexname, indexdef
FROM   pg_indexes
WHERE  schemaname = 'public'
  AND  indexname IN ('hd_quotes_public_token_key', 'hd_work_orders_one_per_quote')
ORDER  BY indexname;

-- Expect the terms snapshot to ALREADY be present on hd_quotes - 19 rows. If any of
-- these is missing, the conversion cannot carry the quote's recorded terms and this
-- migration is incomplete.
SELECT column_name
FROM   information_schema.columns
WHERE  table_schema = 'public' AND table_name = 'hd_quotes'
  AND  column_name IN ('labor_rate', 'parts_markup_percent', 'tax_rate', 'tax_amount',
                       'tax_breakdown', 'travel_hours', 'travel_rate', 'travel_amount',
                       'mileage_miles', 'mileage_rate', 'mileage_amount',
                       'shop_supplies_percent_applied', 'shop_supplies_cap_applied',
                       'shop_supplies_fee', 'diagnostic_fee', 'road_call_fee',
                       'subtotal_labor', 'subtotal_parts', 'total')
ORDER  BY column_name;

-- Expect the status CHECK to already allow approved and declined - it does, and that
-- is why no constraint change is needed here.
SELECT pg_get_constraintdef(oid) AS status_check
FROM   pg_constraint
WHERE  conrelid = 'public.hd_quotes'::regclass
  AND  contype = 'c'
  AND  pg_get_constraintdef(oid) ILIKE '%status%';

-- Expect 0 - nothing is approved or declined yet, and this migration approves nothing.
SELECT count(*) FILTER (WHERE status = 'approved')  AS approved,
       count(*) FILTER (WHERE status = 'declined')  AS declined,
       count(*) FILTER (WHERE public_token IS NOT NULL) AS tokened,
       count(*)                                     AS total_quotes
FROM   public.hd_quotes;

-- Expect 0 - no work order is linked to a quote yet.
SELECT count(*) AS work_orders_with_quote FROM public.hd_work_orders WHERE quote_id IS NOT NULL;

COMMIT;
