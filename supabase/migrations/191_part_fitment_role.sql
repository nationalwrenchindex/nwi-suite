-- 191_part_fitment_role.sql
--
-- WHAT IS MISSING. Brock's belt and filter chart (scripts/data/nwi-fitment-belts-filters.csv)
-- names what each part DOES on each unit in its part_type column: "Drive belt", "Condenser
-- belt", "Generator belt", "Water pump belt", "Fuel filter". That is a fact about the part ON
-- THAT UNIT, not about the part: 78-0803 is the "Motor (jackshaft to compressor) belt" on one
-- unit and the "Compressor to motor belt" on another, and 7 of the chart's 167 parts carry
-- two such names. The Part 3 load (Nov 16) had nowhere to put it, so it was not loaded.
--
-- Without it the counter cannot answer "the drive belt on an SB-200": all three SB-200 belts
-- (78-0629, 78-0603, 78-1341) are part_type 'Belt' in parts, and their descriptions do not say
-- drive / condenser / alternator-water pump. Nor can it tell the C-600 generator belts from its
-- standby motor belts, which are also split only by configuration.
--
-- WHAT THIS DOES.
--   1. Adds public.part_fitment.role TEXT, nullable. No CHECK: it holds the chart's words
--      exactly as charted, nothing normalized or corrected.
--   2. Fills role on the 758 chart rows ONLY (source = 'brock-belt-filter-chart-2026-11-16'),
--      matched on source_row = the CSV line (header = line 1), from the chart's part_type
--      column, verbatim. Generated from the committed CSV, 36 distinct values.
--   - parts.part_type is NOT touched. No other row changes: every row from any other source
--     reads NULL.
--   - No index, trigger, policy or view is touched. part_fitment's RLS policies are per
--     table and cover the new column as they stand.
--
-- The DO block refuses - rolling everything back - unless the chart rows are exactly 758,
-- every one of them has role NULL before and the expected value after, and no other row is
-- touched. Code deploys separately: the counter reads role when the column exists and runs
-- without it (as before) when it does not.
--
-- APPLIED by hand Nov 23, 2026 (Brock: dry run clean - 36 roles, 758 rows - then the COMMIT copy). Plain ASCII.

